export function quizRecommendation(direction: Direction, task: string, timeline: string) {
  const plan = plans[direction][Math.max(0, QUIZ_TASKS[direction].indexOf(task))];
  const pace =
    timeline === "В ближайшее время"
      ? "Начните с минимального пилота по одному сценарию. Сегодня соберите исходные материалы из списка ниже; до запуска согласуйте границы задачи и критерий успеха."
      : timeline === "В течение месяца"
        ? "Разбейте подготовку на этапы: сбор материалов → проектирование → проверка → запуск. На каждом этапе сверяйтесь с критерием успеха; сроки реализации уточняются после оценки задачи."
        : "Пока не запускайте полный проект. Используйте первый шаг как проверку потребности, соберите исходные цифры и сравните ожидаемую пользу с бюджетом.";
  return { ...plan, pace };
}
